using Content.Shared._Crescent.RepairStation;
using Content.Shared.Bank.Components;
using Robust.Client.AutoGenerated;
using Robust.Client.Player;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;
using FancyWindow = Content.Client.UserInterface.Controls.FancyWindow;

namespace Content.Client._Crescent.RepairStation;

[GenerateTypedNameReferences]
public sealed partial class ShipRepairStationWindow : FancyWindow
{
    [Dependency] private readonly IEntityManager _entMan = default!;
    [Dependency] private readonly IGameTiming _timing = default!;
    [Dependency] private readonly IPlayerManager _player = default!;

    public Action<NetEntity>? OnShipSelected;
    public Action? OnStartPressed;
    public Action? OnCancelPressed;

    /// <summary>
    /// Dropdown entry order, so a selection can be turned back into a grid.
    /// </summary>
    private readonly List<NetEntity> _ships = new();

    private ShipRepairStationUiState? _state;

    public ShipRepairStationWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        ShipOption.OnItemSelected += args =>
        {
            ShipOption.SelectId(args.Id);
            if (args.Id >= 0 && args.Id < _ships.Count)
                OnShipSelected?.Invoke(_ships[args.Id]);
        };

        StartButton.OnPressed += _ => OnStartPressed?.Invoke();
        CancelButton.OnPressed += _ => OnCancelPressed?.Invoke();
    }

    /// <summary>
    /// The viewer's own balance, read locally rather than taken from the console's state.
    /// </summary>
    /// <remarks>
    /// The state is one object shared by everyone at the console, so it cannot carry a figure that is
    /// per-viewer. It used to try: the console filled it in for whoever had just clicked, and its
    /// once-a-second refresh - which has no actor behind it - then overwrote it with zero. That made
    /// the authorise button light up on selecting a ship and go dead again a moment later.
    /// </remarks>
    private long GetBalance()
    {
        return _player.LocalEntity is { } player
               && _entMan.TryGetComponent<BankAccountComponent>(player, out var bank)
            ? bank.Balance
            : 0;
    }

    public void UpdateState(ShipRepairStationUiState state)
    {
        _state = state;

        RebuildShipList(state);

        StatusLabel.Text = state.Status switch
        {
            ShipRepairStatus.NoShip => Loc.GetString("ship-repair-station-status-no-ship"),
            ShipRepairStatus.NoBlueprint => Loc.GetString("ship-repair-station-status-no-blueprint"),
            ShipRepairStatus.Intact => Loc.GetString("ship-repair-station-status-intact"),
            ShipRepairStatus.Busy => Loc.GetString("ship-repair-station-status-busy"),
            ShipRepairStatus.Repairing => Loc.GetString("ship-repair-station-status-repairing", ("ship", state.RepairingName ?? string.Empty)),
            _ => Loc.GetString("ship-repair-station-status-quoted"),
        };

        var repairing = state.Status == ShipRepairStatus.Repairing;

        SurveyPanel.Visible = !repairing;
        ProgressPanel.Visible = repairing;

        TilesLabel.Text = state.MissingTiles.ToString();
        StrippedLabel.Text = state.StrippedTiles.ToString();
        PartsLabel.Text = state.MissingParts.ToString();
        DamagedLabel.Text = state.DamagedParts.ToString();
        DecalsLabel.Text = state.Decals.ToString();

        // Mopping and sweeping are one line on the slip; the customer is not interested in which of
        // the two the yard spent its time on.
        CleaningLabel.Text = (state.Spills + state.Debris).ToString();
        RestockLabel.Text = state.Restocks.ToString();
        QuoteLabel.Text = Loc.GetString("ship-repair-station-credits", ("amount", state.Quote));

        ProgressTitleLabel.Text = Loc.GetString("ship-repair-station-working", ("ship", state.RepairingName ?? string.Empty));
        PartsProgressLabel.Text = Loc.GetString("ship-repair-station-parts-progress",
            ("done", state.JobsDone),
            ("total", state.JobsTotal));

        CancelButton.Disabled = !repairing;

        UpdateBalance();
        UpdateProgress();
    }

    /// <summary>
    /// Only touched when the ship list actually changes, so a once-a-second state push cannot collapse
    /// the dropdown out from under whoever has it open.
    /// </summary>
    private void RebuildShipList(ShipRepairStationUiState state)
    {
        var same = _ships.Count == state.Docked.Count;
        if (same)
        {
            for (var i = 0; i < _ships.Count; i++)
            {
                if (_ships[i] == state.Docked[i].Grid)
                    continue;

                same = false;
                break;
            }
        }

        if (!same)
        {
            _ships.Clear();
            ShipOption.Clear();

            for (var i = 0; i < state.Docked.Count; i++)
            {
                var entry = state.Docked[i];
                var label = entry.HasBlueprint
                    ? entry.Name
                    : Loc.GetString("ship-repair-station-ship-unregistered", ("ship", entry.Name));

                ShipOption.AddItem(label, i);
                _ships.Add(entry.Grid);
            }
        }

        ShipOption.Disabled = _ships.Count == 0;

        if (state.Selected is not { } selected)
            return;

        var index = _ships.IndexOf(selected);
        if (index >= 0)
            ShipOption.SelectId(index);
    }

    private void UpdateBalance()
    {
        if (_state is not { } state)
            return;

        var balance = GetBalance();
        BalanceLabel.Text = Loc.GetString("ship-repair-station-credits", ("amount", balance));

        var affordable = state.Quote <= balance;
        StartButton.Disabled = state.Status != ShipRepairStatus.Quoted || !affordable;
        StartButton.ToolTip = affordable ? null : Loc.GetString("ship-repair-station-cannot-afford");
    }

    /// <summary>
    /// Runs off the clock rather than the state pushes, so the bar creeps and the ETA counts down
    /// smoothly between them.
    /// </summary>
    private void UpdateProgress()
    {
        if (_state is not { Status: ShipRepairStatus.Repairing } state)
            return;

        var span = state.EndTime - state.StartTime;
        var elapsed = _timing.CurTime - state.StartTime;

        var fraction = span.TotalSeconds <= 0
            ? 1f
            : Math.Clamp((float) (elapsed.TotalSeconds / span.TotalSeconds), 0f, 1f);

        ProgressBar.Value = fraction;
        PercentLabel.Text = Loc.GetString("ship-repair-station-percent", ("percent", (int) MathF.Round(fraction * 100f)));

        var remaining = state.EndTime - _timing.CurTime;
        if (remaining < TimeSpan.Zero)
            remaining = TimeSpan.Zero;

        EtaLabel.Text = Loc.GetString("ship-repair-station-eta",
            ("time", $"{(int) remaining.TotalMinutes:0}:{remaining.Seconds:00}"));
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        UpdateBalance();
        UpdateProgress();
    }
}
